# Enumerate the specification's 2D mode fields. Use binary weight quantizers only.
function Find-Mode([int]$GridX, [int]$GridY, [int]$WeightBits, [bool]$Dual) {
    $wantedQuant = @(0,0,2,5,8)[$WeightBits]
    for ($mode = 1; $mode -lt 2048; $mode++) {
        $q = ($mode -shr 4) -band 1; $h = ($mode -shr 9) -band 1; $d = ($mode -shr 10) -band 1
        $a = ($mode -shr 5) -band 3; $x = 0; $y = 0
        if (($mode -band 3) -ne 0) {
            $q = $q -bor (($mode -band 3) -shl 1); $b = ($mode -shr 7) -band 3
            switch (($mode -shr 2) -band 3) {
                0 { $x = $b + 4; $y = $a + 2 }
                1 { $x = $b + 8; $y = $a + 2 }
                2 { $x = $a + 2; $y = $b + 8 }
                3 { $b = $b -band 1; if (($mode -band 256) -ne 0) { $x = $b + 2; $y = $a + 2 } else { $x = $a + 2; $y = $b + 6 } }
            }
        } else {
            $q = $q -bor ((($mode -shr 2) -band 3) -shl 1)
            if ((($mode -shr 2) -band 3) -eq 0) { continue }
            $b = ($mode -shr 9) -band 3
            switch (($mode -shr 7) -band 3) {
                0 { $x = 12; $y = $a + 2 }
                1 { $x = $a + 2; $y = 12 }
                2 { $x = $a + 6; $y = $b + 6; $d = 0; $h = 0 }
                3 { if ($a -eq 0) { $x = 6; $y = 10 } elseif ($a -eq 1) { $x = 10; $y = 6 } else { continue } }
            }
        }
        if ($x -eq $GridX -and $y -eq $GridY -and ($q - 2 + 6 * $h) -eq $wantedQuant -and [bool]$d -eq $Dual) { return $mode }
    }
    throw "No mode for $GridX x $GridY / $WeightBits / $Dual"
}
