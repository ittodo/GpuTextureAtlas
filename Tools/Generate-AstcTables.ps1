function Numbers([string]$Text) { return @([regex]::Matches(($Text -replace '//[^\r\n]*',''), '\b\d+\b') | ForEach-Object { [uint32]$_.Value }) }
function Pack-Bytes([object[]]$Bytes) {
    $packed = [Collections.Generic.List[uint32]]::new()
    for ($i = 0; $i -lt $Bytes.Count; $i += 4) {
        [uint32]$value = 0
        for ($j = 0; $j -lt 4 -and ($i + $j) -lt $Bytes.Count; $j++) { $value = $value -bor ([uint32]$Bytes[$i + $j] -shl ($j * 8)) }
        $packed.Add($value)
    }
    return $packed.ToArray()
}
